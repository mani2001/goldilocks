import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const requested = process.argv.slice(2);
const restoring = requested.some(arg => ['--continue', '-c', '--resume', '-r', '--session', '--session-id', '--fork'].includes(arg) || /^(--resume|--session|--session-id|--fork)=/.test(arg));
const modelSpecified = requested.some(arg => ['--provider', '--model'].includes(arg) || /^(--provider|--model)=/.test(arg));
const defaults = restoring || modelSpecified ? [] : ['--provider', 'openai-codex', '--model', 'gpt-6.1-sol', '--thinking', 'high'];
const args = ['--extension', join(root, 'extensions/goldilocks.ts'), '--skill', join(root, 'skills/goldilocks'), ...defaults, ...requested];
const child = spawn('pi', args, { stdio: 'inherit', shell: false, env: process.env });
child.on('error', e => { console.error(`Cannot launch Pi: ${e.message}`); process.exitCode = 1; });
child.on('exit', (code, signal) => { process.exitCode = code ?? (signal ? 1 : 0); });
